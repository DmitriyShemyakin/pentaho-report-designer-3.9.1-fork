  public void reopenAfterRollback(final boolean deepDirty)
  {
    this.open = appliedOpen;
    this.contentRefCount = appliedContentRefCount;
    this.markedOpen = appliedOpen;
    this.markedContentRefCount = appliedContentRefCount;
    this.markedPinPosition = appliedPinPosition;
    resetCacheState(deepDirty);
  }

  protected void makeReusable()
  {
    open = true;
    markedContentRefCount = 0;
    markedOpen = false;
    markedSeen = false;
    markedPinPosition = -1;
    appliedContentRefCount = 0;
    appliedOpen = false;
    appliedSeen = false;
    appliedPinPosition = -1;
    resetCacheState(false);
  }

  public void resetCacheState(final boolean deepDirty)
  {
    setCachedAge(-1);
    if (deepDirty)
    {
      updateCacheState(CACHE_DEEP_DIRTY);
    }
    else
    {
      updateCacheState(CACHE_DIRTY);
    }
    updateChangeTracker();
  }

